"""
Logistic Regression Modeling
============================

Train and evaluate Logistic Regression models for:

- target_6h
- target_12h
- target_24h

Two Logistic Regression variants are compared:

1. Standard Logistic Regression
2. Balanced Logistic Regression
   using class_weight="balanced"

Important:
- PostgreSQL remains the source of truth.
- Temporal datasets are generated by the existing analysis pipeline.
- Chronological train/validation/test splitting is preserved.
- Horizon-specific purge is already applied.
- StandardScaler is fitted ONLY on training data.
- Validation data is used for model comparison.
- Test data remains completely untouched.
"""

import warnings

import numpy as np
import pandas as pd

from sklearn.exceptions import ConvergenceWarning
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from src.analysis.analyze_returns import main as run_analysis_pipeline


# ============================================================
# CONFIGURATION
# ============================================================

TARGET_COLUMNS = [
    "target_6h",
    "target_12h",
    "target_24h",
]

CLASS_ORDER = [
    "DOWN",
    "STABLE",
    "UP",
]


# Majority-class baseline results obtained previously.
# These are validation Macro F1 scores.

BASELINE_MACRO_F1 = {
    "target_6h": 0.200658,
    "target_12h": 0.234304,
    "target_24h": 0.237770,
}


# Features already approved by feature validation.

FEATURE_COLUMNS = [
    "return_1h",
    "return_6h",
    "return_12h",
    "return_24h",
    "volatility_24h",
    "volatility_72h",
    "log_volume_change_1h",
    "log_volume_change_6h",
    "log_volume_change_12h",
    "log_volume_change_24h",
    "other_coins_return_1h",
]


# ============================================================
# METRICS
# ============================================================

def calculate_metrics(
    y_true,
    y_pred,
):
    """
    Calculate model evaluation metrics.
    """

    return {
        "accuracy": accuracy_score(
            y_true,
            y_pred,
        ),

        "balanced_accuracy": balanced_accuracy_score(
            y_true,
            y_pred,
        ),

        "macro_precision": precision_score(
            y_true,
            y_pred,
            labels=CLASS_ORDER,
            average="macro",
            zero_division=0,
        ),

        "macro_recall": recall_score(
            y_true,
            y_pred,
            labels=CLASS_ORDER,
            average="macro",
            zero_division=0,
        ),

        "macro_f1": f1_score(
            y_true,
            y_pred,
            labels=CLASS_ORDER,
            average="macro",
            zero_division=0,
        ),
    }


# ============================================================
# PRINT METRICS
# ============================================================

def print_metrics(
    metrics,
):
    """
    Print validation metrics.
    """

    print(
        f"Accuracy:          "
        f"{metrics['accuracy']:.4f}"
    )

    print(
        f"Balanced Accuracy: "
        f"{metrics['balanced_accuracy']:.4f}"
    )

    print(
        f"Macro Precision:   "
        f"{metrics['macro_precision']:.4f}"
    )

    print(
        f"Macro Recall:      "
        f"{metrics['macro_recall']:.4f}"
    )

    print(
        f"Macro F1:          "
        f"{metrics['macro_f1']:.4f}"
    )


# ============================================================
# CONFUSION MATRIX
# ============================================================

def print_confusion_matrix(
    y_true,
    y_pred,
):
    """
    Print readable confusion matrix.
    """

    matrix = confusion_matrix(
        y_true,
        y_pred,
        labels=CLASS_ORDER,
    )

    matrix_df = pd.DataFrame(
        matrix,
        index=[
            f"actual_{label}"
            for label in CLASS_ORDER
        ],
        columns=[
            f"predicted_{label}"
            for label in CLASS_ORDER
        ],
    )

    print(
        "\nConfusion matrix"
    )

    print(
        "-" * 70
    )

    print(
        matrix_df
    )


# ============================================================
# CLASSIFICATION REPORT
# ============================================================

def print_classification_report(
    y_true,
    y_pred,
):
    """
    Print precision, recall and F1 for every class.
    """

    print(
        "\nPer-class classification report"
    )

    print(
        "-" * 70
    )

    report = classification_report(
        y_true,
        y_pred,
        labels=CLASS_ORDER,
        target_names=CLASS_ORDER,
        digits=4,
        zero_division=0,
    )

    print(
        report
    )


# ============================================================
# TARGET DISTRIBUTION
# ============================================================

def print_target_distribution(
    y,
    split_name,
):
    """
    Show class distribution.
    """

    counts = (
        pd.Series(y)
        .value_counts()
        .reindex(
            CLASS_ORDER,
            fill_value=0,
        )
    )

    percentages = (
        counts
        / counts.sum()
        * 100
    ).round(2)

    distribution = pd.DataFrame(
        {
            "count": counts,
            "percentage": percentages,
        }
    )

    print(
        f"\n{split_name} target distribution"
    )

    print(
        "-" * 70
    )

    print(
        distribution
    )


# ============================================================
# BUILD LOGISTIC MODEL
# ============================================================

def build_logistic_model(
    balanced=False,
):
    """
    Build preprocessing + Logistic Regression pipeline.

    StandardScaler is included inside the pipeline.

    This guarantees the scaler is fitted only when model.fit()
    is called on training data.
    """

    if balanced:

        class_weight = "balanced"

    else:

        class_weight = None

    model = Pipeline(
        steps=[
            (
                "scaler",
                StandardScaler(),
            ),
            (
                "classifier",
                LogisticRegression(
                    class_weight=class_weight,
                    max_iter=2000,
                    solver="lbfgs",
                    random_state=42,
                ),
            ),
        ]
    )

    return model


# ============================================================
# EVALUATE MODEL VARIANT
# ============================================================

def evaluate_model_variant(
    model_name,
    model,
    X_train,
    y_train,
    X_validation,
    y_validation,
    target_column,
):
    """
    Train one model variant and evaluate on Validation.

    Test is intentionally not passed to this function.
    """

    print("\n" + "-" * 70)

    print(
        model_name
    )

    print("-" * 70)

    print(
        f"Training rows:   "
        f"{len(X_train):,}"
    )

    print(
        f"Validation rows: "
        f"{len(X_validation):,}"
    )

    # --------------------------------------------------------
    # Train
    # --------------------------------------------------------

    model.fit(
        X_train,
        y_train,
    )

    # --------------------------------------------------------
    # Validation prediction
    # --------------------------------------------------------

    validation_predictions = (
        model.predict(
            X_validation
        )
    )

    # --------------------------------------------------------
    # Metrics
    # --------------------------------------------------------

    metrics = calculate_metrics(
        y_validation,
        validation_predictions,
    )

    print(
        "\nValidation metrics"
    )

    print(
        "-" * 70
    )

    print_metrics(
        metrics
    )

    # --------------------------------------------------------
    # Compare against majority baseline
    # --------------------------------------------------------

    baseline_f1 = (
        BASELINE_MACRO_F1[
            target_column
        ]
    )

    improvement = (
        metrics["macro_f1"]
        - baseline_f1
    )

    print(
        "\nComparison with majority baseline"
    )

    print(
        "-" * 70
    )

    print(
        f"Baseline Macro F1: "
        f"{baseline_f1:.4f}"
    )

    print(
        f"Model Macro F1:    "
        f"{metrics['macro_f1']:.4f}"
    )

    print(
        f"Difference:        "
        f"{improvement:+.4f}"
    )

    if improvement > 0:

        print(
            "[PASS] Model beats majority baseline."
        )

    elif improvement == 0:

        print(
            "[TIE] Model matches majority baseline."
        )

    else:

        print(
            "[FAIL] Model does not beat majority baseline."
        )

    # --------------------------------------------------------
    # Prediction distribution
    # --------------------------------------------------------

    print_target_distribution(
        validation_predictions,
        "PREDICTED VALIDATION",
    )

    # --------------------------------------------------------
    # Confusion matrix
    # --------------------------------------------------------

    print_confusion_matrix(
        y_validation,
        validation_predictions,
    )

    # --------------------------------------------------------
    # Classification report
    # --------------------------------------------------------

    print_classification_report(
        y_validation,
        validation_predictions,
    )

    return {
        "target_column":
            target_column,

        "model":
            model_name,

        "accuracy":
            metrics[
                "accuracy"
            ],

        "balanced_accuracy":
            metrics[
                "balanced_accuracy"
            ],

        "macro_precision":
            metrics[
                "macro_precision"
            ],

        "macro_recall":
            metrics[
                "macro_recall"
            ],

        "macro_f1":
            metrics[
                "macro_f1"
            ],

        "baseline_macro_f1":
            baseline_f1,

        "macro_f1_improvement":
            improvement,

        "trained_model":
            model,
    }


# ============================================================
# TRAIN ONE HORIZON
# ============================================================

def train_horizon_models(
    dataset,
    target_column,
):
    """
    Train Standard and Balanced Logistic Regression
    for one prediction horizon.
    """

    print("\n" + "=" * 80)

    print(
        f"LOGISTIC REGRESSION - "
        f"{target_column}"
    )

    print("=" * 80)

    train_df = (
        dataset[
            "train"
        ]
        .copy()
    )

    validation_df = (
        dataset[
            "validation"
        ]
        .copy()
    )

    test_df = (
        dataset[
            "test"
        ]
        .copy()
    )

    # --------------------------------------------------------
    # Verify required features
    # --------------------------------------------------------

    missing_features = [
        feature
        for feature in FEATURE_COLUMNS
        if feature not in train_df.columns
    ]

    if missing_features:

        raise ValueError(
            f"Missing features for "
            f"{target_column}: "
            f"{missing_features}"
        )

    # --------------------------------------------------------
    # Extract X and y
    # --------------------------------------------------------

    X_train = (
        train_df[
            FEATURE_COLUMNS
        ]
        .copy()
    )

    y_train = (
        train_df[
            target_column
        ]
        .astype(str)
        .copy()
    )

    X_validation = (
        validation_df[
            FEATURE_COLUMNS
        ]
        .copy()
    )

    y_validation = (
        validation_df[
            target_column
        ]
        .astype(str)
        .copy()
    )

    # --------------------------------------------------------
    # Safety checks
    # --------------------------------------------------------

    if X_train.isna().any().any():

        raise ValueError(
            f"{target_column}: "
            "Training features contain missing values."
        )

    if X_validation.isna().any().any():

        raise ValueError(
            f"{target_column}: "
            "Validation features contain missing values."
        )

    if not np.isfinite(
        X_train.to_numpy()
    ).all():

        raise ValueError(
            f"{target_column}: "
            "Training features contain infinite values."
        )

    if not np.isfinite(
        X_validation.to_numpy()
    ).all():

        raise ValueError(
            f"{target_column}: "
            "Validation features contain infinite values."
        )

    # --------------------------------------------------------
    # Dataset information
    # --------------------------------------------------------

    print(
        f"\nFeatures used: "
        f"{len(FEATURE_COLUMNS)}"
    )

    for feature in FEATURE_COLUMNS:

        print(
            f"  - {feature}"
        )

    print_target_distribution(
        y_train,
        "TRAIN",
    )

    print_target_distribution(
        y_validation,
        "VALIDATION",
    )

    # --------------------------------------------------------
    # Standard Logistic Regression
    # --------------------------------------------------------

    standard_model = (
        build_logistic_model(
            balanced=False
        )
    )

    standard_result = (
        evaluate_model_variant(
            model_name=(
                "Standard Logistic Regression"
            ),
            model=standard_model,
            X_train=X_train,
            y_train=y_train,
            X_validation=X_validation,
            y_validation=y_validation,
            target_column=target_column,
        )
    )

    # --------------------------------------------------------
    # Balanced Logistic Regression
    # --------------------------------------------------------

    balanced_model = (
        build_logistic_model(
            balanced=True
        )
    )

    balanced_result = (
        evaluate_model_variant(
            model_name=(
                "Balanced Logistic Regression"
            ),
            model=balanced_model,
            X_train=X_train,
            y_train=y_train,
            X_validation=X_validation,
            y_validation=y_validation,
            target_column=target_column,
        )
    )

    # --------------------------------------------------------
    # Select best Logistic Regression model
    #
    # Selection is based on Validation Macro F1.
    # Test is NOT used.
    # --------------------------------------------------------

    if (
        balanced_result["macro_f1"]
        >
        standard_result["macro_f1"]
    ):

        best_result = (
            balanced_result
        )

    else:

        best_result = (
            standard_result
        )

    print("\n" + "=" * 70)

    print(
        f"BEST LOGISTIC MODEL - "
        f"{target_column}"
    )

    print("=" * 70)

    print(
        f"Selected model: "
        f"{best_result['model']}"
    )

    print(
        f"Validation Macro F1: "
        f"{best_result['macro_f1']:.4f}"
    )

    print(
        f"Majority baseline Macro F1: "
        f"{best_result['baseline_macro_f1']:.4f}"
    )

    print(
        f"Improvement: "
        f"{best_result['macro_f1_improvement']:+.4f}"
    )

    print(
        "\nTest-set status"
    )

    print(
        "-" * 70
    )

    print(
        f"Test rows available: "
        f"{len(test_df):,}"
    )

    print(
        "Test predictions generated: NO"
    )

    print(
        "Test evaluation performed: NO"
    )

    print(
        "[✓] Test set remains untouched."
    )

    return {
        "standard":
            standard_result,

        "balanced":
            balanced_result,

        "best":
            best_result,
    }


# ============================================================
# FINAL SUMMARY
# ============================================================

def print_final_summary(
    all_results,
):
    """
    Compare the best Logistic Regression model
    across all horizons.
    """

    summary_rows = []

    for (
        target_column,
        results,
    ) in all_results.items():

        best = (
            results[
                "best"
            ]
        )

        summary_rows.append(
            {
                "target_column":
                    target_column,

                "selected_model":
                    best[
                        "model"
                    ],

                "accuracy":
                    best[
                        "accuracy"
                    ],

                "balanced_accuracy":
                    best[
                        "balanced_accuracy"
                    ],

                "macro_precision":
                    best[
                        "macro_precision"
                    ],

                "macro_recall":
                    best[
                        "macro_recall"
                    ],

                "macro_f1":
                    best[
                        "macro_f1"
                    ],

                "baseline_macro_f1":
                    best[
                        "baseline_macro_f1"
                    ],

                "improvement":
                    best[
                        "macro_f1_improvement"
                    ],
            }
        )

    summary_df = pd.DataFrame(
        summary_rows
    )

    print("\n" + "=" * 100)

    print(
        "LOGISTIC REGRESSION SUMMARY"
    )

    print("=" * 100)

    print(
        summary_df.to_string(
            index=False
        )
    )

    print("\n" + "=" * 100)

    print(
        "LOGISTIC REGRESSION PHASE COMPLETE"
    )

    print("=" * 100)

    print(
        "\n[✓] StandardScaler fitted on Train only"
    )

    print(
        "[✓] Standard Logistic Regression trained"
    )

    print(
        "[✓] Balanced Logistic Regression trained"
    )

    print(
        "[✓] Validation used for model comparison"
    )

    print(
        "[✓] Majority baseline comparison completed"
    )

    print(
        "[✓] Macro F1 used for model selection"
    )

    print(
        "[✓] Test sets remain untouched"
    )

    return summary_df


# ============================================================
# MAIN
# ============================================================

def main():
    """
    Run complete Logistic Regression modeling phase.
    """

    print("\n" + "=" * 100)

    print(
        "RUNNING LOGISTIC REGRESSION MODELING PIPELINE"
    )

    print("=" * 100)

    # Ignore convergence warnings while still allowing
    # actual exceptions to stop execution.

    warnings.filterwarnings(
        "ignore",
        category=ConvergenceWarning,
    )

    # --------------------------------------------------------
    # Run existing pipeline:
    #
    # PostgreSQL
    #     ↓
    # EDA
    #     ↓
    # Targets
    #     ↓
    # Features
    #     ↓
    # Leakage validation
    #     ↓
    # Purged temporal datasets
    #
    # --------------------------------------------------------

    temporal_datasets = (
        run_analysis_pipeline()
    )

    if temporal_datasets is None:

        raise ValueError(
            "Temporal datasets were not returned "
            "by analyze_returns.main()."
        )

    all_results = {}

    # --------------------------------------------------------
    # Train each horizon separately
    # --------------------------------------------------------

    for target_column in TARGET_COLUMNS:

        if (
            target_column
            not in temporal_datasets
        ):

            raise KeyError(
                f"{target_column} "
                "was not found in temporal datasets."
            )

        results = (
            train_horizon_models(
                temporal_datasets[
                    target_column
                ],
                target_column,
            )
        )

        all_results[
            target_column
        ] = results

    # --------------------------------------------------------
    # Final summary
    # --------------------------------------------------------

    summary_df = (
        print_final_summary(
            all_results
        )
    )

    return {
        "results":
            all_results,

        "summary":
            summary_df,
    }


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()