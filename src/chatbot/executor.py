"""
Execution layer for the AlphaPulse chatbot.

Responsibilities:
- Execute only prediction calls approved by the planner.
- Reuse the existing AlphaPulse prediction controller.
- Read verified market data from PostgreSQL.
- Collect real model outputs.
- Never ask the LLM to generate prediction values.
- Never convert model confidence/probability into investment return.

Flow:

    User prompt
        ->
    intent_parser
        ->
    planner
        ->
    executor
        ->
    prediction controller / PostgreSQL
        ->
    verified AlphaPulse data
"""

from __future__ import annotations
from sqlalchemy import text
from typing import Any

from src.chatbot.schemas import (
    ChatResult,
    ExecutionPlan,
    IntentType,
    PredictionCall,
    SUPPORTED_COINS,
    SUPPORTED_HORIZONS,
)

from src.controllers.prediction_controller import (
    get_prediction,
)
from src.infrastructure.database.connection import engine


# ============================================================
# SAFETY LIMITS
# ============================================================

MAX_PREDICTION_CALLS = 5


# ============================================================
# FINAL EXECUTION VALIDATION
# ============================================================

def validate_prediction_call(
    call: PredictionCall,
) -> None:
    """
    Perform a final validation immediately before a model call.
    """

    if not isinstance(call, PredictionCall):
        raise TypeError(
            "Executor received an invalid prediction call."
        )

    coin = str(call.coin).strip().upper()

    if coin not in SUPPORTED_COINS:
        raise ValueError(
            f"Unsupported cryptocurrency: {coin}"
        )

    if call.horizon_hours not in SUPPORTED_HORIZONS:
        raise ValueError(
            f"Unsupported prediction horizon: "
            f"{call.horizon_hours} hours."
        )


# ============================================================
# SINGLE PREDICTION
# ============================================================

def execute_prediction_call(
    call: PredictionCall,
) -> dict[str, Any]:
    """
    Execute one approved prediction through AlphaPulse's
    existing prediction controller.

    No LLM is involved in the numerical/model prediction.
    """

    validate_prediction_call(call)

    result = get_prediction(
        asset=call.coin,
        horizon_hours=call.horizon_hours,
    )

    if not isinstance(result, dict):
        raise ValueError(
            "AlphaPulse prediction controller returned "
            "an invalid result."
        )

    return result


# ============================================================
# MULTIPLE PREDICTIONS
# ============================================================

def execute_prediction_calls(
    calls: list[PredictionCall],
) -> list[dict[str, Any]]:
    """
    Execute all approved model calls in an execution plan.
    """

    if len(calls) > MAX_PREDICTION_CALLS:
        raise ValueError(
            f"Executor allows a maximum of "
            f"{MAX_PREDICTION_CALLS} prediction calls."
        )

    results: list[dict[str, Any]] = []

    for call in calls:
        result = execute_prediction_call(call)
        results.append(result)

    return results


# ============================================================
# MARKET DATA
# ============================================================

def validate_market_coin(
    coin: str,
) -> str:
    """
    Validate a coin before using it in a database query.
    """

    normalized_coin = str(coin).strip().upper()

    if normalized_coin not in SUPPORTED_COINS:
        raise ValueError(
            f"Unsupported cryptocurrency: {normalized_coin}"
        )

    return normalized_coin


def get_latest_market_data(
    coins: list[str],
) -> list[dict[str, Any]]:
    """
    Read the latest verified market snapshot from PostgreSQL
    for each requested supported coin.

    Prices are never generated by the LLM.

    The query uses the same market_snapshots table that powers
    the existing AlphaPulse /api/market-data endpoint.
    """

    if not coins:
        return []

    normalized_coins: list[str] = []

    for coin in coins:
        normalized_coin = validate_market_coin(coin)

        if normalized_coin not in normalized_coins:
            normalized_coins.append(normalized_coin)

    placeholders = ", ".join(
        f":coin_{index}"
        for index in range(len(normalized_coins))
    )

    parameters = {
        f"coin_{index}": coin
        for index, coin in enumerate(normalized_coins)
    }

    query = f"""
        SELECT DISTINCT ON (UPPER(c.symbol))
            ms.coin_id,
            UPPER(c.symbol) AS symbol,
            c.name,
            ms.timestamp,
            ms.current_price,
            ms.market_cap,
            ms.market_cap_rank,
            ms.total_volume,
            ms.high_24h,
            ms.low_24h,
            ms.price_change_24h,
            ms.price_change_percentage_24h,
            ms.circulating_supply,
            ms.total_supply,
            ms.max_supply,
            ms.fetched_at
        FROM market_snapshots AS ms
        INNER JOIN coins AS c
            ON c.coin_id = ms.coin_id
        WHERE UPPER(c.symbol) IN ({placeholders})
        ORDER BY
            UPPER(c.symbol),
            ms.timestamp DESC
    """

    with engine.connect() as connection:
        result = connection.execute(
                text(query),
                parameters,
            )
        
        rows = [
            dict(row._mapping)
            for row in result
            ]

    

    # Convert timestamps into JSON-friendly strings here so the
    # chatbot layer remains safe even outside the FastAPI endpoint.
    for row in rows:

        timestamp = row.get("timestamp")

        if timestamp is not None:
            row["timestamp"] = timestamp.isoformat()

        fetched_at = row.get("fetched_at")

        if fetched_at is not None:
            row["fetched_at"] = fetched_at.isoformat()

    return rows


# ============================================================
# STANDARD MESSAGES
# ============================================================

def irrelevant_message() -> str:
    """
    Response for questions outside AlphaPulse's scope.
    """

    return (
        "I can help with AlphaPulse cryptocurrency predictions, "
        "market analysis, supported-coin comparisons, current "
        "market information, and model-based investment scenarios. "
        "I can't answer unrelated questions."
    )


def capability_message() -> str:
    """
    Describe capabilities that are actually implemented.
    """

    return (
        "AlphaPulse supports BTC, ETH, SOL, XRP and ADA. "
        "Its trained prediction models currently support "
        "6-hour, 12-hour and 24-hour trend predictions. "
        "I can retrieve the latest stored market prices, compare "
        "supported coins, and explain model signals using "
        "verified AlphaPulse data."
    )


def investment_limitation_message(
    amount: float | None,
    currency: str,
) -> str:
    """
    Explain why a categorical trend prediction cannot be
    converted into an invented future dollar value.
    """

    if amount is None:
        return (
            "AlphaPulse can evaluate the model signal for this "
            "investment scenario, but the current model predicts "
            "direction rather than a numeric future return. "
            "Therefore I won't invent a profit or final value."
        )

    formatted_amount = f"{amount:,.2f}"

    return (
        f"For the {currency} {formatted_amount} scenario, "
        "AlphaPulse can provide the model's predicted direction "
        "and confidence together with verified market data. "
        "The current model does not predict an exact percentage "
        "return, so an exact future profit or portfolio value "
        "cannot be calculated without inventing a return."
    )


# ============================================================
# MAIN EXECUTOR
# ============================================================

def execute_plan(
    plan: ExecutionPlan,
) -> ChatResult:
    """
    Execute a deterministic AlphaPulse chatbot plan.

    The LLM determines intent only.

    Numerical predictions come from the trained AlphaPulse model.
    Market prices come from PostgreSQL.
    """

    if not isinstance(plan, ExecutionPlan):
        raise TypeError(
            "execute_plan expects an ExecutionPlan object."
        )

    intent = plan.intent

    # --------------------------------------------------------
    # Irrelevant question
    # --------------------------------------------------------

    if intent.intent_type == IntentType.IRRELEVANT:

        return ChatResult(
            success=True,
            intent=intent,
            predictions=[],
            market_data=[],
            message=irrelevant_message(),
        )

    # --------------------------------------------------------
    # Unsupported request
    # --------------------------------------------------------

    if not intent.is_supported:

        return ChatResult(
            success=False,
            intent=intent,
            predictions=[],
            market_data=[],
            message=(
                intent.unsupported_reason
                or
                "This request is not currently supported "
                "by AlphaPulse."
            ),
        )

    # --------------------------------------------------------
    # Capability question
    # --------------------------------------------------------

    if intent.intent_type == IntentType.CAPABILITY:

        return ChatResult(
            success=True,
            intent=intent,
            predictions=[],
            market_data=[],
            message=capability_message(),
        )

    # --------------------------------------------------------
    # Retrieve verified market data when required
    # --------------------------------------------------------

    market_data: list[dict[str, Any]] = []

    try:

        if plan.needs_market_data:

            market_data = get_latest_market_data(
                intent.coins
            )

    except Exception as exc:

        return ChatResult(
            success=False,
            intent=intent,
            predictions=[],
            market_data=[],
            message=None,
            error=(
                "Unable to retrieve verified market data: "
                f"{exc}"
            ),
        )

    # --------------------------------------------------------
    # Current price request
    # --------------------------------------------------------

    if intent.intent_type == IntentType.CURRENT_PRICE:

        if not market_data:

            return ChatResult(
                success=False,
                intent=intent,
                predictions=[],
                market_data=[],
                message=(
                    "No verified market snapshot is currently "
                    "available for the requested cryptocurrency."
                ),
            )

        return ChatResult(
            success=True,
            intent=intent,
            predictions=[],
            market_data=market_data,
            message=None,
        )

    # --------------------------------------------------------
    # Execute real model calls
    # --------------------------------------------------------

    try:

        predictions = execute_prediction_calls(
            plan.prediction_calls
        )

    except Exception as exc:

        return ChatResult(
            success=False,
            intent=intent,
            predictions=[],
            market_data=market_data,
            message=None,
            error=str(exc),
        )

    # --------------------------------------------------------
    # Investment scenario
    # --------------------------------------------------------

    if intent.intent_type == IntentType.INVESTMENT_PROJECTION:

        return ChatResult(
            success=True,
            intent=intent,
            predictions=predictions,
            market_data=market_data,
            message=investment_limitation_message(
                amount=intent.investment_amount,
                currency=intent.currency,
            ),
        )

    # --------------------------------------------------------
    # Normal prediction/comparison/analysis result
    # --------------------------------------------------------

    return ChatResult(
        success=True,
        intent=intent,
        predictions=predictions,
        market_data=market_data,
        message=None,
    )